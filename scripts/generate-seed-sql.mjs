/**
 * Writes supabase/seed.sql from src/lib/seed-data.ts, for when you'd rather
 * paste SQL into the Supabase editor than run `npm run seed`.
 *
 *   node scripts/generate-seed-sql.mjs
 */
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import * as seed from "../src/lib/seed-data.ts";

const q = (v) => (v === null || v === undefined ? "null" : `'${String(v).replace(/'/g, "''")}'`);
const arr = (xs) => `array[${xs.map(q).join(", ")}]::text[]`;
const json = (v) => `${q(JSON.stringify(v))}::jsonb`;

const out = [
  "-- Generated by scripts/generate-seed-sql.mjs — do not edit by hand.",
  "-- Run supabase/schema.sql first, then paste this into the Supabase SQL editor.",
  "",
  "insert into public.services (slug, title, copy, image, icon, points, sort_order, published) values",
  seed.services
    .map(
      (s) =>
        `  (${q(s.slug)}, ${q(s.title)}, ${q(s.copy)}, ${q(s.image)}, ${q(s.icon)}, ${arr(s.points)}, ${s.sort_order}, true)`,
    )
    .join(",\n") +
    "\non conflict (slug) do update set title = excluded.title, copy = excluded.copy," +
    " image = excluded.image, icon = excluded.icon, points = excluded.points," +
    " sort_order = excluded.sort_order, updated_at = now();",
  "",
  "insert into public.clients (name, logo, website, sort_order, published) values",
  seed.clients
    .map((c) => `  (${q(c.name)}, ${q(c.logo)}, ${q(c.website)}, ${c.sort_order}, true)`)
    .join(",\n") +
    "\non conflict (name) do update set logo = excluded.logo, website = excluded.website," +
    " sort_order = excluded.sort_order;",
  "",
  "insert into public.gallery_categories (slug, title, copy, sort_order, published) values",
  seed.gallery
    .map((g) => `  (${q(g.slug)}, ${q(g.title)}, ${q(g.copy)}, ${g.sort_order}, true)`)
    .join(",\n") +
    "\non conflict (slug) do update set title = excluded.title, copy = excluded.copy," +
    " sort_order = excluded.sort_order;",
  "",
  "delete from public.gallery_images;",
  "insert into public.gallery_images (category_slug, url, caption, sort_order, published) values",
  seed.gallery
    .flatMap((g) =>
      g.images.map((i) => `  (${q(g.slug)}, ${q(i.url)}, ${q(i.caption)}, ${i.sort_order}, true)`),
    )
    .join(",\n") + ";",
  "",
  "delete from public.testimonials;",
  "insert into public.testimonials (quote, name, org, sort_order, published) values",
  seed.testimonials
    .map((t) => `  (${q(t.quote)}, ${q(t.name)}, ${q(t.org)}, ${t.sort_order}, true)`)
    .join(",\n") + ";",
  "",
  "insert into public.site_settings (key, value) values",
  Object.entries(seed.siteSettings)
    .map(([k, v]) => `  (${q(k)}, ${json(v)})`)
    .join(",\n") + "\non conflict (key) do update set value = excluded.value, updated_at = now();",
  "",
].join("\n");

const dest = join(dirname(fileURLToPath(import.meta.url)), "..", "supabase", "seed.sql");
writeFileSync(dest, out);
console.log(`Wrote ${dest}`);
